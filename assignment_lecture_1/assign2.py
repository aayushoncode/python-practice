#take two numbers as input from the user and print their sum, difference, product, and quotient

num1=int(input("enter your first number : "))
num2=int(input("enter your second number : "))

print(f"the sum of two number is {num1+num2}")
print(f"the difference of two number is {num1-num2}")
print(f"the product of two number is {num1*num2}")
print(f"the quotient of two number is {num1//num2}")